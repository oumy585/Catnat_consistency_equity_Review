        print(f"{m}σ | cutoff {cut:.4f} | zones {pos+neg} ({100*(pos+neg)/len(st50):.1f}%) | "
              f"under {neg} ({100*neg/(pos+neg):.1f}%) | over {pos} ({100*pos/(pos+neg):.1f}%) | mean|HG| {mean_abs:.4f}")

